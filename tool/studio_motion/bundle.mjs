// A deliberately small bundler for the pinned Studio modules' named ESM imports.
// No npm download or upstream checkout is needed to reproduce the shipped asset.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const vendor = path.join(root, 'third_party/yachiyo-live2d-studio');
const provenance = JSON.parse(fs.readFileSync(path.join(vendor, 'SOURCE.json')));
const quickjs = path.join(root, 'packages/tsukuyomi_studio_motion/src/vendor/quickjs');
for (const [name, expected] of Object.entries(JSON.parse(fs.readFileSync(path.join(quickjs, 'SOURCE.json'))).files)) {
  assertHash(path.join(quickjs, name), expected);
}
function assertHash(file, expected) {
  if (crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex') !== expected) {
    throw new Error(`Modified upstream source: ${file}`);
  }
}
for (const [name, expected] of Object.entries(provenance.files)) {
  assertHash(path.join(vendor, name), expected);
}
const modules = new Map();
function visit(file) {
  const id = path.relative(root, file).replaceAll('\\', '/');
  if (modules.has(id)) return id;
  modules.set(id, '');
  let source = fs.readFileSync(file, 'utf8');
  source = source.replace(/^import\s+\{([\s\S]*?)\}\s+from\s+['"]([^'"]+)['"];?/gm, (_, names, specifier) => {
    let dependency = path.resolve(path.dirname(file), specifier);
    if (!path.extname(dependency)) dependency += '.js';
    if (!dependency.startsWith(vendor + path.sep)) throw new Error(`Unexpected import: ${dependency}`);
    return `const {${names.replace(/\s+as\s+/g, ':')}} = __load(${JSON.stringify(visit(dependency))});`;
  });
  const names = [];
  source = source.replace(/^export\s+(function|const|let|class)\s+(\w+)/gm, (_, kind, name) => {
    names.push(name); return `${kind} ${name}`;
  }).replace(/^export\s+\{([^}]+)\};?/gm, (_, list) => {
    names.push(...list.split(',').map(x => x.trim()).filter(Boolean)); return '';
  });
  if (/^\s*(?:import|export)\s/m.test(source)) throw new Error(`Unsupported ESM syntax in ${id}`);
  modules.set(id, `function(__exports, __load) {\n${source}\nObject.assign(__exports, {${names.join(',')}});\n}`);
  return id;
}
const entry = visit(path.join(root, 'tool/studio_motion/entry.js'));
const code = `// Studio ${provenance.commit}; generated by tool/studio_motion/bundle.mjs.\n` +
  `// MIT notices: assets/live2d/studio-motion.LICENSE.txt\n(() => {\nconst __modules = {\n` +
  [...modules].map(([id, source]) => `${JSON.stringify(id)}: ${source}`).join(',\n') +
  `\n};\nconst __cache = {};\nfunction __load(id) { if (__cache[id]) return __cache[id]; const value = __cache[id] = {}; __modules[id](value, __load); return value; }\n__load(${JSON.stringify(entry)});\n})();\n`;
const output = path.join(root, 'assets/live2d/studio-motion.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== code) throw new Error('Studio bundle is stale');
} else {
  fs.writeFileSync(output, code);
  fs.writeFileSync(path.join(root, 'assets/live2d/studio-motion.LICENSE.txt'),
    `Yachiyo Live2D Studio ${provenance.commit}\n${provenance.repository}\n\n` +
    fs.readFileSync(path.join(vendor, 'LICENSE'), 'utf8') + '\n' +
    fs.readFileSync(path.join(vendor, 'licenses/uLipSync-MIT.txt'), 'utf8'));
}
console.log(`Studio: ${modules.size - 1} unchanged upstream modules, ${Buffer.byteLength(code)} bytes`);
